// Copies what the site serves from the repo root into the build, so the root
// stays the single source of truth:
//
//   ../install.sh, ../uninstall.sh            -> generated/scripts.ts
//   ../app/Resources/Silkscreen-Regular.ttf   -> generated/Silkscreen-Regular.ttf
//
// and gathers every language's error page words, the `errors` of each
// messages/<code>.json, into generated/errors.ts: the error pages run in the
// browser, and should not carry every language's whole page with them.
//
// Runs before `dev` and `build`. Fails loudly when a source is missing, so a
// deploy never ships without the installer. `generated/` is gitignored.
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const site = join(dirname(fileURLToPath(import.meta.url)), "..");
const root = join(site, "..");
const out = join(site, "generated");

function need(path) {
  if (!existsSync(path)) {
    console.error(`sync: missing ${path}`);
    console.error("sync: the site builds from the Wham repo, so its root files must be there.");
    console.error("sync: on Vercel, turn on \"Include files outside the root directory\".");
    process.exit(1);
  }
  return path;
}

const install = readFileSync(need(join(root, "install.sh")), "utf8");
const uninstall = readFileSync(need(join(root, "uninstall.sh")), "utf8");
const font = need(join(root, "app", "Resources", "Silkscreen-Regular.ttf"));

if (!install.startsWith("#!/bin/sh") || !uninstall.startsWith("#!/bin/sh")) {
  console.error("sync: install.sh and uninstall.sh must be shell scripts");
  process.exit(1);
}

mkdirSync(out, { recursive: true });
writeFileSync(
  join(out, "scripts.ts"),
  [
    "// Generated by scripts/sync.mjs from the repo root. Do not edit.",
    `export const INSTALL_SH = ${JSON.stringify(install)};`,
    `export const UNINSTALL_SH = ${JSON.stringify(uninstall)};`,
    "",
  ].join("\n"),
);
copyFileSync(font, join(out, "Silkscreen-Regular.ttf"));

const messages = join(site, "messages");
const errors = Object.fromEntries(
  readdirSync(messages)
    .filter((file) => file.endsWith(".json"))
    .map((file) => [file.replace(".json", ""), JSON.parse(readFileSync(join(messages, file), "utf8")).errors]),
);
writeFileSync(
  join(out, "errors.ts"),
  [
    "// Generated by scripts/sync.mjs from messages/*.json. Do not edit.",
    'import type { Locale, Messages } from "@/lib/i18n";',
    "",
    `export const ERRORS: Record<Locale, Messages["errors"]> = ${JSON.stringify(errors, null, 2)};`,
    "",
  ].join("\n"),
);
console.log("sync: install.sh, uninstall.sh, Silkscreen and the error pages' words copied into generated/");
